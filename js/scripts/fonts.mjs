// Builds src/_fonts.ts: the font smlibpy's Text uses by default (src/smlibpy/fonts), as base64,
// so text works synchronously in Node and in the browser without file access. Copies the font's
// license to fonts/OFL.txt (it goes with the font wherever the font goes).
//
// Builds src/_brotli_dictionary.ts too: the static dictionary of Brotli (RFC 7932, appendix A),
// which WOFF2 fonts are compressed with, from smlibpy's copy (src/smlibpy/_brotli_dictionary.bin),
// zlib-compressed (_inflate.ts unpacks it) and as base64.
//
//     node scripts/fonts.mjs

import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { deflateSync } from 'node:zlib'

const js = join(dirname(fileURLToPath(import.meta.url)), '..')
const fonts = join(js, '..', 'src', 'smlibpy', 'fonts')
const name = 'Lato-Regular.ttf'

const data = readFileSync(join(fonts, name))
const license = readFileSync(join(fonts, 'OFL.txt'), 'utf8')
// the notice above the license text: the font, its copyright and its license
const notice = []
for (const line of license.split(/\r?\n/)) {
  if (line.startsWith('This Font Software is licensed')) break
  if (line.trim()) notice.push(line.trim())
}

const base64 = data.toString('base64')
const lines = []
for (let i = 0; i < base64.length; i += 100) lines.push(base64.slice(i, i + 100))

const out = [
  `// Generated by scripts/fonts.mjs from src/smlibpy/fonts/${name}: do not edit.`,
  '//',
  ...notice.map((line) => `// ${line}`),
  '// The license: fonts/OFL.txt.',
  '',
  `/** ${name} (${data.length} bytes), base64 (line breaks are ignored when it is decoded). */`,
  'export const LATO_REGULAR = `',
  ...lines,
  '`',
  '',
].join('\n')

const target = join(js, 'src', '_fonts.ts')
writeFileSync(target, out)
mkdirSync(join(js, 'fonts'), { recursive: true })
copyFileSync(join(fonts, 'OFL.txt'), join(js, 'fonts', 'OFL.txt'))
console.log(`${relative(js, target)}: ${name}, ${data.length} bytes; fonts/OFL.txt`)

// the Brotli dictionary
const DICTIONARY_SHA256 = '20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70' // RFC 7932, appendix A
const words = readFileSync(join(js, '..', 'src', 'smlibpy', '_brotli_dictionary.bin'))
if (createHash('sha256').update(words).digest('hex') !== DICTIONARY_SHA256) throw new Error('the Brotli dictionary is damaged')
const packed = deflateSync(words, { level: 9 }).toString('base64')
const rows = []
for (let i = 0; i < packed.length; i += 100) rows.push(packed.slice(i, i + 100))
const dictionary = [
  '// Generated by scripts/fonts.mjs from src/smlibpy/_brotli_dictionary.bin: do not edit.',
  '//',
  '// The static dictionary of Brotli (RFC 7932, appendix A), from github.com/google/brotli:',
  '// Copyright (c) 2009, 2010, 2013-2016 by the Brotli Authors. Licensed under the MIT License (see NOTICE).',
  '',
  `/** The dictionary (${words.length} bytes, SHA-256 ${DICTIONARY_SHA256}), zlib-compressed, base64 (line breaks are ignored when it is decoded). */`,
  'export const BROTLI_DICTIONARY = `',
  ...rows,
  '`',
  '',
].join('\n')
const dictTarget = join(js, 'src', '_brotli_dictionary.ts')
writeFileSync(dictTarget, dictionary)
console.log(`${relative(js, dictTarget)}: the Brotli dictionary, ${words.length} bytes (${packed.length} in base64)`)
