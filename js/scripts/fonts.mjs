// Builds src/_fonts.ts: the font smlibpy's Text uses by default (src/smlibpy/fonts), as base64,
// so text works synchronously in Node and in the browser without file access. Copies the font's
// license to fonts/OFL.txt (it goes with the font wherever the font goes).
//
//     node scripts/fonts.mjs

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const js = join(dirname(fileURLToPath(import.meta.url)), '..')
const fonts = join(js, '..', 'src', 'smlibpy', 'fonts')
const name = 'Lato-Regular.ttf'

const data = readFileSync(join(fonts, name))
const license = readFileSync(join(fonts, 'OFL.txt'), 'utf8')
// the notice above the license text: the font, its copyright and its license
const notice = []
for (const line of license.split(/\r?\n/)) {
  if (line.startsWith('This Font Software is licensed')) break
  if (line.trim()) notice.push(line.trim())
}

const base64 = data.toString('base64')
const lines = []
for (let i = 0; i < base64.length; i += 100) lines.push(base64.slice(i, i + 100))

const out = [
  `// Generated by scripts/fonts.mjs from src/smlibpy/fonts/${name}: do not edit.`,
  '//',
  ...notice.map((line) => `// ${line}`),
  '// The license: fonts/OFL.txt.',
  '',
  `/** ${name} (${data.length} bytes), base64 (line breaks are ignored when it is decoded). */`,
  'export const LATO_REGULAR = `',
  ...lines,
  '`',
  '',
].join('\n')

const target = join(js, 'src', '_fonts.ts')
writeFileSync(target, out)
mkdirSync(join(js, 'fonts'), { recursive: true })
copyFileSync(join(fonts, 'OFL.txt'), join(js, 'fonts', 'OFL.txt'))
console.log(`${relative(js, target)}: ${name}, ${data.length} bytes; fonts/OFL.txt`)
