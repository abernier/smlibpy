// -------------------------------------------------------------------------------- options
/**
 * Checks the options object of the public function `name` as Python checks keyword arguments,
 * with a TypeError: it is a plain object (or left out), and every key is an option of `name`
 * (OPTIONS, made from smlibpy's signatures; a name that is not there takes none). Keys that start
 * with _ are smlibwasm's own. `count`, the number of arguments given (`arguments.length`), also
 * checks that there are no more than the positional parameters and the options.
 */
export function _opts(name: string, options: unknown, count = -1): void {
  const [positional, keys] = OPTIONS[name] ?? [-1, []]
  const takes = (given: number) =>
    `${name}() takes ${positional} positional argument${positional === 1 ? '' : 's'} but ${given} ${given === 1 ? 'was' : 'were'} given`
  if (options != null && !isPlainObject(options)) {
    if (positional >= 0) throw new TypeError(takes(Math.max(count, positional + 1)))
    throw new TypeError(`${name}(): the options must be an object, not ${typeof options}`)
  }
  if (positional >= 0 && count > positional + 1) throw new TypeError(takes(options == null ? count : count - 1))
  if (options == null) return
  for (const key of Object.keys(options)) {
    if (key.startsWith('_') || keys.includes(key)) continue
    let hint: string
    const camel = key.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase())
    const near = keys
      .map((k) => [_distance(k.toLowerCase(), key.toLowerCase()), k] as const)
      .filter(([d, k]) => d <= Math.floor((k.length + 3) / 4))
      .sort((x, y) => x[0] - y[0])
    if (keys.includes(camel)) hint = `; did you mean '${camel}'? (the options are camelCase)`
    else if (near.length) hint = `; did you mean '${near[0][1]}'?`
    else if (keys.length) hint = ` (its options: ${keys.join(', ')})`
    else hint = ' (it takes no options)'
    throw new TypeError(`${name}() got an unexpected option '${key}'${hint}`)
  }
}

/** The edit distance of two words (insertions, deletions, substitutions). */
function _distance(a: string, b: string): number {
  let row = Array.from({ length: b.length + 1 }, (_, j) => j)
  for (let i = 1; i <= a.length; i++) {
    const next = [i]
    for (let j = 1; j <= b.length; j++) next.push(Math.min(row[j] + 1, next[j - 1] + 1, row[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)))
    row = next
  }
  return row[b.length]
}
