# Going down and across the topology
part = Box(40, 30, 20) - Cylinder(6, 30)
top = part.faces().top().one()
print("[05] top face:", top)
print("[05] top.owner is part:", top.owner is part, type(top.owner).__name__)
print("[05] top.edges:", len(top.edges()), [e.geom_type for e in top.edges()])
print("[05] top.vertices:", len(top.vertices()))
print("[05] top.wires:", len(top.wires()), top.wires())
ow = top.outer_wire(); iw = top.inner_wires()
print("[05] outer_wire:", ow, "closed", ow.is_closed, "len", round(ow.length, 4))
print("[05] inner_wires:", iw, type(iw).__name__)
print("[05] neighbors:", len(top.neighbors()), sorted(f.geom_type for f in top.neighbors()))
cyl = part.faces().cylinders().one()
print("[05] cyl.edges:", cyl.edges(), " seams:", cyl.edges(seams=True))
print("[05] cyl.wires:", cyl.wires())
print("[05] cyl outer_wire edges:", cyl.outer_wire().edges())
print("[05] cyl inner_wires:", cyl.inner_wires())
print("[05] cyl.neighbors:", cyl.neighbors())
e = part.edges().parallel_to(Z).first
print("[05] edge faces:", e.faces(), " vertices:", e.vertices())
seam = [x for x in part.edges(seams=True) if x.is_seam]
print("[05] seam edges:", seam, " seam.faces:", [s.faces() for s in seam])
v = part.vertices().top().right().back().one()
print("[05] vertex:", v, "edges", len(v.edges()), "faces", len(v.faces()))
# ShapeList expansion: unique
print("[05] faces().edges():", len(part.faces().edges()), " faces().vertices():", len(part.faces().vertices()))
print("[05] top|bottom faces().edges():", len((part.faces().top() + part.faces().bottom()).edges()))
print("[05] edges().faces() of top edges:", len(part.edges().top().faces()))
print("[05] wires of list:", len(part.faces().wires()))
# outer wire edge orientation: is the loop chained?
ws = ow.edges()
print("[05] outer chained:", all(ws[i].end.is_close(ws[(i+1) % len(ws)].start, 1e-6) for i in range(len(ws))))
print("[05] outer wire plane normal:", ow.plane().z_dir.to_tuple())
print("[05] bottom outer wire plane normal:", part.faces().bottom().one().outer_wire().plane().z_dir.to_tuple())
print("[05] inner wire plane normal:", iw[0].plane().z_dir.to_tuple())
# edges taken from a wire of a face still belong to the part: can they be filleted?
r = part.fillet(top.outer_wire().edges(), 2)
print("[05] fillet outer wire edges:", round(r.volume, 3), r.is_valid())
# solids
two = Box(10, 10, 10) + Box(10, 10, 10).translate(30, 0, 0)
print("[05] two solids:", len(two.solids()), [round(s.volume, 3) for s in two.solids()], [s.center().x for s in two.solids()])
print("[05] two faces:", len(two.faces()))
print("[05] solid faces owner:", two.solids()[0].faces()[0].owner is two)
