# Empty selections: what each consumer does with them
box = Box(20, 20, 10)
empty = box.edges().circles()
print("[03] empty:", empty, len(empty), bool(empty))
def tryit(label, fn):
    try:
        r = fn()
        print(f"[03] {label}: OK ->", r if not hasattr(r, "volume") else f"{type(r).__name__} vol={round(r.volume, 3)}")
    except Exception as e:
        print(f"[03] {label}: {type(e).__name__}: {e}")
tryit("chain top()", lambda: empty.top())
tryit("chain parallel_to", lambda: empty.parallel_to(Z).sort_by(X).group_by(Z))
tryit("max_by", lambda: empty.max_by(Z))
tryit("one()", lambda: empty.one())
tryit("first", lambda: empty.first)
tryit("last", lambda: empty.last)
tryit("[0]", lambda: empty[0])
tryit("largest", lambda: empty.largest())
tryit("smallest", lambda: empty.smallest())
tryit("nearest", lambda: empty.nearest((0, 0, 0)))
tryit("center", lambda: empty.center())
tryit("bbox", lambda: empty.bbox())
tryit("fillet empty", lambda: box.fillet(empty, 1))
tryit("chamfer empty", lambda: box.chamfer(empty, 1))
tryit("on(empty)", lambda: Circle(2).on(box.faces().cylinders()))
tryit("on(two faces)", lambda: Circle(2).on(box.faces().parallel_to(Z)))
tryit("on(one face)", lambda: Circle(2).on(box.faces().top()).center())
tryit("shell openings empty", lambda: box.shell(1, openings=box.faces().cylinders()))
tryit("fillet ShapeList of one", lambda: box.fillet(box.edges().parallel_to(Z).right().back(), 1))
tryit("fillet a single Edge", lambda: box.fillet(box.edges().parallel_to(Z).first, 1))
tryit("fillet a face", lambda: box.fillet(box.faces().top(), 1))
tryit("box - empty", lambda: box - ShapeList())
tryit("box + []", lambda: box + [])
tryit("several: one()", lambda: box.faces().parallel_to(Z).one())
