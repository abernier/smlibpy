# convex / concave / smooth: which edges count as what
def report(label, p):
    E = p.edges()
    c, cc, s = E.convex(), E.concave(), E.smooth()
    print(f"[09] {label}: edges {len(E)} convex {len(c)} concave {len(cc)} smooth {len(s)}")
    return c, cc, s
report("Box", Box(10, 10, 10))
L = Box(20, 10, 10, align=Align.MIN) + Box(10, 10, 20, align=Align.MIN)
c, cc, s = report("L-shape", L)
print("[09]   concave edge:", cc, " midpoint", cc.one().center().to_tuple())
pocket = Box(30, 30, 10) - Box(10, 10, 5, align=(Align.CENTER, Align.CENTER, Align.MIN))
c, cc, s = report("pocket", pocket)
print("[09]   concave: parZ", len(cc.parallel_to(Z)), " horizontal", len(cc.perpendicular_to(Z)))
hole = Box(20, 20, 10) - Cylinder(3, 20)
c, cc, s = report("through hole", hole)
print("[09]   hole rims convexity:", [e.convexity for e in hole.edges().circles()])
boss = Box(30, 30, 10) + Cylinder(5, 10).translate(0, 0, 10)
c, cc, s = report("boss", boss)
print("[09]   boss base circle:", [(round(e.center().z, 3), e.convexity) for e in boss.edges().circles()])
fil = Box(20, 20, 10).fillet(Box(20, 20, 10).edges().parallel_to(Z), 3)
c, cc, s = report("filleted vertical", fil)
print("[09]   smooth types:", sorted(e.geom_type for e in s))
fil2 = L.fillet(L.edges().concave(), 2)
c, cc, s = report("L filleted concave", fil2)
print("[09]   L fillet vol:", round(L.volume, 3), "->", round(fil2.volume, 3), "valid", fil2.is_valid())
cham = Box(20, 20, 10).chamfer(Box(20, 20, 10).edges().top(), 2)
report("chamfered top", cham)
sh = Box(20, 20, 10).shell(1, openings=Box(20, 20, 10).faces().top())
c, cc, s = report("shelled open top", sh)
print("[09]   shell concave are inside:", all(abs(e.center().x) < 10 and abs(e.center().y) < 10 for e in cc))
sheet = Rectangle(10, 10)
print("[09] sketch edges convexity:", [e.convexity for e in sheet.edges()])
print("[09] free Line convexity:", Line((0, 0, 0), (1, 0, 0)).convexity, Line((0, 0, 0), (1, 0, 0)).is_convex())
print("[09] is_convex on L concave edge:", L.edges().concave().one().is_convex())
# a cylinder crossing a cylinder (curved-curved edge)
cross = Cylinder(5, 30) + Cylinder(5, 30).rotate(X, 90)
c, cc, s = report("cross cylinders", cross)
print("[09]   cross edge types:", sorted(e.geom_type for e in cc))
# sphere on a box: circular intersection, concave
sb = Box(20, 20, 10) + Sphere(6).translate(0, 0, 5)
c, cc, s = report("sphere on box", sb)
