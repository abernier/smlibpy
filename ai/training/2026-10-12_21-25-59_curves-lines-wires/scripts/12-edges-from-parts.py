# Edges taken from parts are Edges too: wires from them, outer_wire, sketch from them
box = Box(40, 20, 10)
top = box.faces().top()
ow = top.outer_wire() if not isinstance(top, list) else top[0].outer_wire()
print("[12] outer_wire:", ow, ow.start, "plane z", ow.plane().z_dir)
w = Wire(box.edges().top())
print("[12] Wire(box.edges().top()):", w, w.is_closed)
s = w.to_sketch()
print("[12] to_sketch: area", s.area, "plane", s.plane.origin, s.plane.z_dir)
# a curve drawn onto a face
c = Polyline((-5, -5), (5, -5), (5, 5), close=True).on(box.faces().top())
print("[12] wire on top face bbox:", c.bbox().min, c.bbox().max)
front = box.faces().facing(-Y)
cf = Line((0, 0), (10, 0)).on(front)
print("[12] line on front face:", cf, "front face plane x", front[0].plane.x_dir, "z", front[0].plane.z_dir)
side = box.faces().facing(X)
cs = Line((0, 0), (10, 0)).on(side)
print("[12] line on +X face:", cs, "plane x", side[0].plane.x_dir)
cs2 = Line((0, 0), (0, 5)).on(side)
print("[12] line (0,0)->(0,5) on +X face:", cs2)
