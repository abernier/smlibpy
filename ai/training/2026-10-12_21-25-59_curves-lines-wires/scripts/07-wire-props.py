# Wire properties: length, point_at, tangent_at, center, bbox, reversed, close, plane, vertices
w = Wire([Line((0, 0), (10, 0)), CenterArc((10, 5), 5, -90, 180), Line((10, 10), (0, 10))])
print("[07]", w, "closed", w.is_closed)
print("[07] length:", w.length, "expected", 20 + 5 * math.pi)
for t in (0, 0.25, 0.5, 0.75, 1.0, -0.5, 1.5):
    print(f"[07] t={t}: point {w.point_at(t)} tangent {w.tangent_at(t)}")
print("[07] center (length weighted):", w.center())
print("[07] bbox:", w.bbox().min, w.bbox().max)
print("[07] vertices:", len(w.vertices()), [v.point.to_tuple() for v in w.vertices()])
r = w.reversed()
print("[07] reversed:", r.start, r.end, "tangent(0)", r.tangent_at(0), [e.geom_type for e in r.edges()])
print("[07] plane of open wire:", w.plane().origin, w.plane().z_dir)
c = w.close()
print("[07] close():", c, c.edges()[-1])
print("[07] close of closed is same:", c.close() is c)
print("[07] plane of closed ccw:", c.plane().z_dir, "cw:", c.reversed().plane().z_dir)
print("[07] distance_to (5,5):", c.distance_to((5, 5)))
sk = c.to_sketch()
print("[07] to_sketch area:", sk.area, "expected", 100 + math.pi * 25 / 2, "plane z", sk.plane.z_dir)
skr = c.reversed().to_sketch()
print("[07] reversed to_sketch area:", skr.area, "plane z", skr.plane.z_dir)
print("[07] edges and wires:", len(w.edges()), len(w.wires()))
print("[07] faces of wire:", w.faces() if hasattr(w, "faces") else None)
