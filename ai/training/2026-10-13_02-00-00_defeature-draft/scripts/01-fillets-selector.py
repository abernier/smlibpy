# ShapeList.fillets(): which faces count as fillets, max_radius
box = Box(40, 30, 20)
v4 = box.fillet(box.edges().parallel_to(Z), 3)
rounded = box.fillet(box.edges(), 3)
print("[01] v4:", len(v4.faces().fillets()), sorted({f.geom_type for f in v4.faces().fillets()}))
found = rounded.faces().fillets()
print("[01] all edges r3:", len(found), {t: len([f for f in found if f.geom_type == t]) for t in ("cylinder", "sphere")})
print("[01] max_radius 3 / 2.9:", len(rounded.faces().fillets(max_radius=3)), len(rounded.faces().fillets(max_radius=2.9)))
print("[01] plain box:", len(box.faces().fillets()), "hole walls:", len((box - Cylinder(5, 40)).faces().fillets()))
disc = Cylinder(10, 8)
disc = disc.fillet(disc.edges(), 2)
print("[01] disc rounded both ends:", [f.geom_type for f in disc.faces().fillets()], "max_radius 1.9:", len(disc.faces().fillets(max_radius=1.9)))
slot = Slot(40, 12).extrude(5)
print("[01] slot ends:", len(slot.faces().fillets()), "with max_radius=5:", len(slot.faces().fillets(max_radius=5)))
plate = Box(60, 40, 5, align=(Align.CENTER, Align.CENTER, Align.MAX))
boss = plate + Box(20, 16, 10, align=(Align.CENTER, Align.CENTER, Align.MIN))
boss = boss.fillet(boss.edges().filter(lambda e: abs(e.center().z) < 1e-6 and e.convexity == "concave"), 2)
print("[01] boss base fillets:", sorted((f.geom_type, round(f.area, 3)) for f in boss.faces().fillets()))
g2 = box.fillet(box.edges().parallel_to(Z), 3, continuity="G2")
print("[01] G2 blends:", len(g2.faces().fillets()), "max_radius=2:", len(g2.faces().fillets(max_radius=2)))
var = box.fillet(box.edges().parallel_to(Z), (2, 4))
print("[01] variable 2..4:", len(var.faces().fillets()), "max_radius=3:", len(var.faces().fillets(max_radius=3)))
print("[01] chained:", len(rounded.faces().fillets().cylinders()), len(rounded.faces().fillets().top()))
try:
    box.faces().fillets(max_radius=0)
except ValueError as e:
    print("[01] error:", e)
import time
t = time.time(); rounded.faces().fillets(); print("[01] time 26 faces: %.3f s" % (time.time() - t))
