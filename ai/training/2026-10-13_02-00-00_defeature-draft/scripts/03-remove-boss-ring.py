# Part.remove_fillets between a boss and a plate, ring fillets, convex and concave together
plate = Box(60, 40, 5, align=(Align.CENTER, Align.CENTER, Align.MAX))
sharp = plate + Box(20, 16, 10, align=(Align.CENTER, Align.CENTER, Align.MIN))
part = sharp.fillet(sharp.edges().filter(lambda e: abs(e.center().z) < 1e-6 and e.convexity == "concave"), 2)
back = part.remove_fillets()
print("[03] boss base r2:", len(part.faces()), "->", len(back.faces()), "volume", round(part.volume, 6), "->", round(back.mass_properties(accuracy=1e-10).volume, 9), "sharp", sharp.volume)
cyl = plate + Cylinder(6, 10, align=(Align.CENTER, Align.CENTER, Align.MIN))
ring = cyl.fillet(cyl.edges().filter(lambda e: abs(e.center().z) < 1e-6 and e.geom_type == "circle"), 2)
back = ring.remove_fillets()
exact = 12000 + math.pi * 36 * 10
print("[03] ring r2:", [f.geom_type for f in ring.faces().fillets()], len(ring.faces()), "->", len(back.faces()),
      "volume error %.1e" % (back.mass_properties(accuracy=1e-10).volume - exact))
both = cyl.fillet(cyl.edges().filter(lambda e: e.geom_type == "circle" and e.center().z > 9), 2)
both = both.fillet(both.edges().filter(lambda e: e.geom_type == "circle" and abs(e.center().z) < 1e-6), 1.5)
print("[03] boss with round top r2 and base fillet r1.5:", len(both.faces().fillets()), "up to 1.5:", len(both.faces().fillets(max_radius=1.5)))
back = both.remove_fillets()
print("[03]   all:", len(both.faces()), "->", len(back.faces()), "volume error %.1e" % (back.mass_properties(accuracy=1e-10).volume - exact))
small = both.remove_fillets(max_radius=1.5)
print("[03]   max_radius=1.5:", len(small.faces()), "faces, volume", round(both.volume, 4), "->", round(small.volume, 4))
puck = Cylinder(10, 8)
pr = puck.fillet(puck.edges(), 2)
print("[03] disc rounded both ends: volume error %.1e" % (pr.remove_fillets().mass_properties(accuracy=1e-10).volume - math.pi * 100 * 8))
hb = Box(40, 30, 10) - Cylinder(6, 20)
hr = hb.fillet(hb.edges().filter(lambda e: e.geom_type == "circle"), 1.5)
print("[03] rounded hole rims: volume error %.1e" % (hr.remove_fillets().mass_properties(accuracy=1e-10).volume - (12000 - math.pi * 36 * 10)))
