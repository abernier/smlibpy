# distance_to and closest_point between bodies and points: outside, inside, nested, touching.
import time
def tryit(label, f):
    try:
        t = time.perf_counter()
        r = f()
        print(f"[01] {label}: {r!r} ({1000*(time.perf_counter()-t):.1f} ms)")
    except Exception as e:
        print(f"[01] {label}: {type(e).__name__}: {e}")
a = Box(10, 10, 10)
b = Sphere(3).translate(20, 0, 0)
tryit("box-sphere gap (exp 12)", lambda: a.distance_to(b))
tryit("sphere-box (reverse)", lambda: b.distance_to(a))
tryit("box to point (0,0,30) (exp 25)", lambda: a.distance_to((0, 0, 30)))
tryit("closest_point (0,0,30)", lambda: a.closest_point((0, 0, 30)))
tryit("box to point inside (1,2,3)", lambda: a.distance_to((1, 2, 3)))
tryit("closest_point inside (1,2,3)", lambda: a.closest_point((1, 2, 3)))
tryit("box to point on face (5,0,0)", lambda: a.distance_to((5, 0, 0)))
tryit("box to corner direction (10,10,10) (exp sqrt(75))", lambda: (a.distance_to((10, 10, 10)), math.sqrt(75)))
tryit("closest_point (10,10,10)", lambda: a.closest_point((10, 10, 10)))
tryit("box to box overlapping", lambda: a.distance_to(Box(10, 10, 10).translate(5, 0, 0)))
tryit("box to box touching face", lambda: a.distance_to(Box(10, 10, 10).translate(10, 0, 0)))
tryit("box to small sphere inside (r2 at 0, exp wall 3)", lambda: a.distance_to(Sphere(2)))
tryit("small sphere inside to box", lambda: Sphere(2).distance_to(a))
tryit("big sphere r20 containing box (exp 20-sqrt(75))", lambda: (Sphere(20).distance_to(a), 20 - math.sqrt(75)))
tryit("box to Vertex", lambda: a.distance_to(Vertex(0, 0, 30)))
tryit("Vertex to box", lambda: Vertex(0, 0, 30).distance_to(a))
tryit("box to Vector", lambda: a.distance_to(Vector(0, 0, 30)))
tryit("box to Edge", lambda: a.distance_to(Line((0, 0, 30), (10, 0, 30))))
tryit("box to Shell (face at z=30)", lambda: a.distance_to(Box(4, 4, 4).faces().top().one().to_shell().translate(0, 0, 28)))
tryit("box to Sketch on z=20", lambda: a.distance_to(Rectangle(4, 4).on(Plane.XY.offset(20))))
tryit("Sketch to point", lambda: Rectangle(4, 4).distance_to((0, 0, 7)))
tryit("Sketch closest_point", lambda: Rectangle(4, 4).closest_point((10, 0, 7)))
tryit("box to list of parts", lambda: a.distance_to([b]))
