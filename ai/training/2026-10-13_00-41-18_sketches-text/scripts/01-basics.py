# Text: what comes back, how big, which edges
t = Text("SMLIB 42", 8)
print("[01] type:", type(t).__name__, "| plane:", t.plane.origin, t.plane.z_dir)
print("[01] faces:", len(t.faces()), "holes:", sorted(len(f.inner_wires()) for f in t.faces()))
print("[01] area:", round(t.area, 4), "| bbox:", t.bbox())
print("[01] edge kinds:", sorted({e.geom_type for e in t.edges()}), "edges:", len(t.edges()))
o = Text("O", 10)
print("[01] O edges:", [e.geom_type for e in o.edges()], "closed:", [e.is_closed for e in o.edges()])
p = o.extrude(2)
print("[01] O extruded: faces", len(p.faces()), "valid", p.is_valid(), "volume", round(p.volume, 4), "= 2 * area", round(2 * o.area, 4))
h = Text("H", 10)
print("[01] H: edges", len(h.edges()), sorted({e.geom_type for e in h.edges()}), "height", h.bbox().size.y)
