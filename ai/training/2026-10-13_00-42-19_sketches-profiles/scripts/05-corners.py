# Sketch.fillet and Sketch.chamfer of corners chosen by geometry; vertex convexity.
import math
def show(label, s):
    print(f"[05] {label}: area {s.area:.4f} edges {len(s.edges())} {sorted(set(e.geom_type for e in s.edges()))}")
angle = Polygon((0, 0), (40, 0), (40, 8), (8, 8), (8, 30), (0, 30))
print("[05] L convexity", [(round(v.x), round(v.y), v.convexity) for v in angle.vertices()])
print("[05] convex", len(angle.vertices().convex()), "concave", len(angle.vertices().concave()))
inner = angle.fillet(4, angle.vertices().concave())
show("L, inner corner r 4", inner)
print("[05]   closed form", round(496 + (4 - math.pi) * 16 / 4, 4))
outer = inner.chamfer(1, inner.vertices().convex())
show("then the 5 outer corners chamfered 1", outer)
print("[05]   closed form", round(496 + (4 - math.pi) * 4 - 5 * 0.5, 4), "smooth corners", len(outer.vertices().smooth()))
show("all corners r 2", angle.fillet(2))
plate = Rectangle(60, 40) - Rectangle(20, 10)
print("[05] plate with square hole:", len(plate.vertices().convex()), "convex,", len(plate.vertices().concave()), "concave")
show("hole corners only (concave), r 2", plate.fillet(2, plate.vertices().concave()))
show("outline only (convex), r 5", plate.fillet(5, plate.vertices().convex()))
show("one corner by point", Rectangle(40, 20).fillet(5, [(20, 10)]))
show("right end by selector", Rectangle(30, 10).fillet(5, Rectangle(30, 10).vertices().right()))
rc = Rectangle(30, 20) + Pos(15, 0) * Circle(6)
print("[05] rectangle + circle corners", [v.convexity for v in rc.vertices()])
show("line-arc corners filleted r 2", rc.fillet(2, rc.vertices().concave()))
show("line-arc corners chamfered 1", rc.chamfer(1, rc.vertices().concave()))
lens = Circle(10) & Pos(10, 0) * Circle(10)
show("lens (arc-arc corners) fillet 2", lens.fillet(2))
show("lens chamfer 2", lens.chamfer(2))
show("free function fillet", fillet(plate.vertices().concave(), 1))
show("free function chamfer", chamfer(plate.vertices().convex(), 1))
placed = Rectangle(20, 10).on(Plane.XZ)
show("placed on XZ, top corners r 2", placed.fillet(2, placed.vertices().top()))
print("[05] placed top corners at", [v.point for v in placed.vertices().top()])
def err(label, f):
    try:
        f(); print(f"[05] {label}: no error")
    except Exception as e:
        print(f"[05] {label}: {type(e).__name__}: {e}")
err("not a corner", lambda: plate.fillet(2, [(1, 2)]))
err("too large", lambda: plate.fillet(30))
err("too large one edge", lambda: Rectangle(40, 20).fillet(10.5))
err("no sharp corners", lambda: Slot(30, 10).fillet(1))
err("smooth corner given", lambda: Slot(30, 10).fillet(1, [(10, 5)]))
err("spline corner", lambda: (make_face(Spline((0, 0), (10, 5), (20, 0), tangents=((0, 1), (0, -1))) + Line((20, 0), (0, 0)))).fillet(1))
err("radius 0", lambda: plate.fillet(0))
err("chamfer too long", lambda: Rectangle(10, 10).chamfer(6))
err("edges instead of vertices", lambda: plate.fillet(1, plate.edges()))
err("part vertex convexity", lambda: Box(1, 1, 1).vertices()[0].convexity)
